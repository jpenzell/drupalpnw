// Generates guarded copies of the 12 paid legacy functions into gate/functions/<name>/index.ts
// (outside the deploy path). Run: bun gate/scripts/generate-guarded.ts  [--check]
// The transform is mechanical and verified by gate/test/guarded.test.ts:
//   1. import the guard; 2. CORS origin "*" -> the allowed PNW2 origin;
//   3. right after the OPTIONS preflight, refuse requests without a verified+introspected attendee
//      token (interactive enabled) or a password-authorized presenter.
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

export const GUARDED_FUNCTIONS = [
  "josh-gpt",
  "live-ai-demo",
  "multi-ai-estimate",
  "pick-number",
  "presentation-ai-assistant",
  "probability-words-live",
  "probability-words-persona",
  "random-number-demo",
  "regenerate-era-image",
  "scene-rehearsal",
  "test-prompt",
  "transform-headshot",
] as const;

// Deliberately NOT guarded: free captions/translation, presenter password check, platform email hooks.
export const UNGUARDED_FUNCTIONS = ["translate-caption", "verify-password", "auth-email-hook", "preview-transactional-email"] as const;

export const GUARD_IMPORT = 'import { denyWithoutInteractiveAccess, PNW2_CORS_ORIGIN } from "../_shared/guardRuntime.ts";';
export const GUARD_LINES = ["  const denied = await denyWithoutInteractiveAccess(req);", "  if (denied) return denied;"];

const ROOT = join(dirname(new URL(import.meta.url).pathname), "..", "..");

export function transform(name: string, source: string): string {
  const hash = createHash("sha256").update(source).digest("hex");
  let text = source;

  const originRe = /(["'])Access-Control-Allow-Origin\1\s*:\s*(["'])\*\2/g;
  if ((text.match(originRe) ?? []).length !== 1) throw new Error(`${name}: expected exactly one wildcard CORS origin`);
  text = text.replace(originRe, `$1Access-Control-Allow-Origin$1: PNW2_CORS_ORIGIN`);

  // Attendee tokens travel as Authorization: Bearer (already an allowed header) — no header change.

  const lines = text.split("\n");
  const opt = lines.findIndex((l) => /req\.method\s*===\s*["']OPTIONS["']/.test(l));
  if (opt < 0) throw new Error(`${name}: no OPTIONS preflight`);
  let insertAt: number;
  if (/return\s/.test(lines[opt])) {
    insertAt = opt + 1;
  } else {
    const close = lines.findIndex((l, i) => i > opt && l.trim() === "}");
    if (close < 0 || close - opt > 3) throw new Error(`${name}: unexpected OPTIONS block shape`);
    insertAt = close + 1;
  }
  const serveLine = lines.slice(0, opt).reverse().find((l) => /serve\(/.test(l)) ?? "";
  if (!/async\s*\(\s*req\b/.test(serveLine)) throw new Error(`${name}: serve handler is not async (req)`);
  lines.splice(insertAt, 0, ...GUARD_LINES);

  const lastImport = lines.reduce((acc, l, i) => (/^import\s/.test(l) ? i : acc), -1);
  lines.splice(lastImport + 1, 0, GUARD_IMPORT);

  const banner = [
    `// GENERATED by gate/scripts/generate-guarded.ts from supabase/functions/${name}/index.ts`,
    `// source-sha256: ${hash}`,
    "// STAGED — not deployed. Replaces the original only at Stage 4 (gate/README.md).",
  ];
  return [...banner, ...lines].join("\n");
}

export function sourceOf(name: string): string {
  return readFileSync(join(ROOT, "supabase", "functions", name, "index.ts"), "utf8");
}

export function outputPath(name: string): string {
  return join(ROOT, "gate", "functions", name, "index.ts");
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const name of GUARDED_FUNCTIONS) {
    const out = transform(name, sourceOf(name));
    if (check) {
      let current = "";
      try { current = readFileSync(outputPath(name), "utf8"); } catch { /* missing */ }
      if (current !== out) { stale++; console.error(`stale: ${name}`); }
    } else {
      mkdirSync(dirname(outputPath(name)), { recursive: true });
      writeFileSync(outputPath(name), out);
      console.log(`wrote gate/functions/${name}/index.ts`);
    }
  }
  if (check && stale) process.exit(1);
}
